# CREATE USER ACCOUNT
# ==================================================

def create_user(
    full_name,
    email,
    mobile,
    password,
    role,
    course,
    year=None,
    branch=None,
    department=None,
    roll_number=None,
    section=None
):

    full_name = (full_name or "").strip()
    email = (email or "").strip().lower()
    mobile = (mobile or "").strip()
    role = (role or "").strip().lower()
    course = (course or "").strip()

    year = (year or "").strip() or None
    section = (section or "").strip().upper() or None
    branch = (branch or "").strip() or None
    department = (department or "").strip() or None
    roll_number = (roll_number or "").strip() or None

    if not full_name:
        raise ValueError("Please enter your full name.")

    if not email:
        raise ValueError("Please enter your email address.")

    if not mobile:
        raise ValueError("Please enter your mobile number.")

    if not password:
        raise ValueError("Please enter your password.")

    if len(password) < 8:
        raise ValueError("Password must contain at least 8 characters.")

    if role not in VALID_ROLES:
        raise ValueError("Invalid account role.")

    if course not in VALID_COURSES:
        raise ValueError("Please select a valid course.")

    if not mobile.isdigit() or len(mobile) != 10:
        raise ValueError("Enter a valid 10-digit mobile number.")

    if role in ("student", "staff") and not year:
        raise ValueError("Please select your year.")

    if role == "hod":
        section = None

    elif role in ("student", "staff"):

        if section not in VALID_SECTIONS:
            raise ValueError("Please select a valid section (A-F).")

    if role == "student" and not roll_number:
        raise ValueError("Student roll number is required.")

    approval_status = "APPROVED" if role == "hod" else "PENDING"

    password_hash = generate_password_hash(password)

    conn = get_db()

    try:

        cursor = conn.execute("""
            INSERT INTO users (
                full_name,
                email,
                mobile,
                password_hash,
                role,
                course,
                year,
                branch,
                department,
                section,
                roll_number,
                approval_status
            )
            VALUES (
                %s, %s, %s, %s, %s, %s,
                %s, %s, %s, %s, %s, %s
            )
        """, (
            full_name,
            email,
            mobile,
            password_hash,
            role,
            course,
            year,
            branch,
            department,
            section,
            roll_number,
            approval_status
        ))

        conn.commit()

        return cursor.lastrowid

    except psycopg.IntegrityError as exc:

        conn.rollback()

        if "email" in str(exc).lower():
            raise ValueError(
                "This email is already registered."
            ) from exc

        raise

    finally:
        conn.close()


