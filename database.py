# SHOW ALL REGISTERED USERS
# ==================================================

def show_all_users():

    conn = get_db()

    try:

        users = conn.execute("""
            SELECT
                id,
                full_name,
                email,
                role,
                course,
                department
            FROM users
            ORDER BY id
        """).fetchall()

        print("\n========== REGISTERED USERS ==========")

        if not users:
            print("No users found in this database.")

        for user in users:

            print(
                f"ID: {user['id']} | "
                f"Name: {user['full_name']} | "
                f"Email: {user['email']} | "
                f"Role: {user['role']} | "
                f"Course: {user['course']} | "
                f"Department: {user['department']}"
            )

    finally:
        conn.close()


