# ==================================================
# DATABASE CONFIGURATION
# ==================================================

DATABASE_URL = os.environ.get("DATABASE_URL")

VALID_COURSES = ("BTech", "MBA", "MTech", "BCA")
VALID_ROLES = ("student", "staff", "hod")
VALID_SECTIONS = ("A", "B", "C", "D", "E", "F")


# ==================================================
# SQLITE COMPATIBILITY CURSOR
# ==================================================

class CursorWrapper:

    def __init__(self, cursor, lastrowid=None):
        self.cursor = cursor
        self.lastrowid = lastrowid

    @property
    def rowcount(self):
        return self.cursor.rowcount

    def fetchone(self):
        return self.cursor.fetchone()

    def fetchall(self):
        return self.cursor.fetchall()

    def close(self):
        self.cursor.close()


# ==================================================
# SQLITE COMPATIBILITY CONNECTION
# ==================================================

class ConnectionWrapper:

    def __init__(self, connection):
        self.connection = connection

    @staticmethod
    def convert_query(query):
        return re.sub(r"\?", "%s", query)

    def execute(self, query, params=()):

        query = self.convert_query(query)
        params = tuple(params or ())

        is_insert = bool(
            re.match(r"^\s*INSERT\b", query, re.IGNORECASE)
        )

        has_returning = bool(
            re.search(r"\bRETURNING\b", query, re.IGNORECASE)
        )

        if is_insert and not has_returning:
            query = query.rstrip().rstrip(";") + " RETURNING id"

        cursor = self.connection.execute(query, params)

        lastrowid = None

        if is_insert and not has_returning:
            row = cursor.fetchone()

            if row:
                lastrowid = row["id"]

        return CursorWrapper(cursor, lastrowid)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


# ==================================================
# DATABASE CONNECTION
# ==================================================

def get_db():

    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL environment variable is missing."
        )

    connection = psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=15
    )

    return ConnectionWrapper(connection)


# ==================================================
# INITIALIZE DATABASE
# ==================================================

def init_db():

    conn = get_db()

    try:

        # USERS TABLE
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (

                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                full_name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                mobile TEXT NOT NULL,
                password_hash TEXT NOT NULL,

                role TEXT NOT NULL
                    CHECK (role IN ('student', 'staff', 'hod')),

                course TEXT NOT NULL
                    CHECK (course IN ('BTech', 'MBA', 'MTech', 'BCA')),

                year TEXT,
                branch TEXT,
                department TEXT,
                section TEXT,
                roll_number TEXT,

                approval_status TEXT NOT NULL DEFAULT 'PENDING'
                    CHECK (
                        approval_status IN (
                            'PENDING',
                            'APPROVED',
                            'REJECTED'
                        )
                    ),

                profile_photo TEXT,

                is_active INTEGER NOT NULL DEFAULT 1,

                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
            )
        """)

        # COMPLAINTS TABLE
        conn.execute("""
            CREATE TABLE IF NOT EXISTS complaints (

                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                student_id BIGINT NOT NULL,
                assigned_staff_id BIGINT,
                assigned_hod_id BIGINT,

                title TEXT NOT NULL,
                description TEXT NOT NULL,

                course TEXT NOT NULL,
                year TEXT NOT NULL,
                branch TEXT NOT NULL,
                department TEXT NOT NULL,
                section TEXT,

                attachment TEXT,

                status TEXT NOT NULL DEFAULT 'SUBMITTED'
                    CHECK (
                        status IN (
                            'SUBMITTED',
                            'IN_PROGRESS',
                            'FORWARDED_TO_HOD',
                            'SOLUTION_SENT_TO_STAFF',
                            'RESOLVED',
                            'REJECTED'
                        )
                    ),

                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (student_id)
                    REFERENCES users(id),

                FOREIGN KEY (assigned_staff_id)
                    REFERENCES users(id),

                FOREIGN KEY (assigned_hod_id)
                    REFERENCES users(id)
            )
        """)

        # COMPLAINT SOLUTIONS TABLE
        conn.execute("""
            CREATE TABLE IF NOT EXISTS complaint_solutions (

                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                complaint_id BIGINT NOT NULL,
                author_id BIGINT NOT NULL,

                solution TEXT NOT NULL,

                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (complaint_id)
                    REFERENCES complaints(id) ON DELETE CASCADE,

                FOREIGN KEY (author_id)
                    REFERENCES users(id)
            )
        """)

        # NOTIFICATIONS TABLE
        conn.execute("""
            CREATE TABLE IF NOT EXISTS notifications (

                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                user_id BIGINT NOT NULL,
                complaint_id BIGINT,

                message TEXT NOT NULL,

                is_read INTEGER NOT NULL DEFAULT 0,

                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (user_id)
                    REFERENCES users(id),

                FOREIGN KEY (complaint_id)
                    REFERENCES complaints(id) ON DELETE CASCADE
            )
        """)

        # COMPLAINT STATUS HISTORY TABLE
        conn.execute("""
            CREATE TABLE IF NOT EXISTS complaint_status_history (

                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                complaint_id BIGINT NOT NULL,

                status TEXT NOT NULL,
                remarks TEXT,

                updated_by BIGINT,

                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (complaint_id)
                    REFERENCES complaints(id) ON DELETE CASCADE,

                FOREIGN KEY (updated_by)
                    REFERENCES users(id)
            )
        """)

        # ==================================================
        # DATABASE MIGRATIONS
        # ==================================================

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS is_active INTEGER NOT NULL DEFAULT 1
        """)

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS section TEXT
        """)

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS roll_number TEXT
        """)

        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS profile_photo TEXT
        """)

        conn.execute("""
            ALTER TABLE complaints
            ADD COLUMN IF NOT EXISTS section TEXT
        """)

        # ==================================================
        # DATABASE INDEXES
        # ==================================================

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_users_course_department
            ON users(course, year, department, role)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_users_course_year_section
            ON users(course, year, section, role, approval_status)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_complaints_student
            ON complaints(student_id)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_complaints_status
            ON complaints(status)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_complaints_section
            ON complaints(course, year, section, status)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_notifications_user
            ON notifications(user_id, is_read)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_complaint_history
            ON complaint_status_history(complaint_id, created_at)
        """)

        conn.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower
            ON users(LOWER(email))
        """)

        conn.commit()

        print("Supabase PostgreSQL database initialized successfully!")

    except Exception:
        conn.rollback()
        raise

    finally:
        conn.close()


